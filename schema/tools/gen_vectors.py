def invalid_records() -> list[dict]:
    base = bytes.fromhex(VALID_RECORDS[0]["hex"])

    bad_crc = bytearray(base)
    bad_crc[-1] ^= 0x01

    bad_version = bytearray(base)
    bad_version[0] = 2
    # CRC is recomputed so the version check, not the CRC check, must fire.
    bad_version[18:20] = struct.pack("<H", crc16_ccitt_false(bytes(bad_version[:18])))

    return [
        {"name": "short_input", "hex": base[:-1].hex(), "error": "short_input"},
        {"name": "unsupported_version", "hex": bytes(bad_version).hex(), "error": "unsupported_version"},
        {"name": "bad_crc", "hex": bytes(bad_crc).hex(), "error": "bad_crc"},
    ]


def build_records_json() -> str:
    doc = {
        "format": "record",
        "version": RECORD_VERSION,
        "size": RECORD_SIZE,
        "crc": {"name": "CRC-16/CCITT-FALSE", "check_input": "123456789", "check": "29b1"},
        "valid": VALID_RECORDS,
        "invalid": invalid_records(),
    }
    return json.dumps(doc, indent=2) + "\n"


def c_bytes(b: bytes) -> str:
    return ", ".join(f"0x{x:02x}" for x in b)


def c_float(v: float) -> str:
    s = repr(float(v))
    if "e" in s or "E" in s:
        s = f"{v:.1f}"
    return s + "f"


def build_records_header() -> str:
    lines = [
        "// Generated by schema/tools/gen_vectors.py. Do not edit.",
        "#pragma once",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
        f"#define RECORD_VECTOR_VERSION {RECORD_VERSION}",
        f"#define RECORD_VECTOR_SIZE {RECORD_SIZE}",
        "",
        "struct RecordVector {",
        "    const char* name;",
        f"    uint8_t bytes[{RECORD_SIZE}];",
        "    uint8_t version, type, quality, flags;",
        "    uint32_t seq, time;",
        "    float value;",
        "    uint16_t boot_id;",
        "};",
        "",
        "static const RecordVector kRecordVectors[] = {",
    ]
    for v in VALID_RECORDS:
        r = v["record"]
        lines.append(
            f'    {{"{v["name"]}", {{{c_bytes(bytes.fromhex(v["hex"]))}}}, '
            f'{r["version"]}, {r["type"]}, {r["quality"]}, {r["flags"]}, '
            f'{r["seq"]}u, {r["time"]}u, {c_float(r["value"])}, {r["boot_id"]}}},'
        )
    lines += [
        "};",
        f"static const size_t kRecordVectorCount = {len(VALID_RECORDS)};",
        "",
        "struct InvalidRecordVector {",
        "    const char* name;",
        "    size_t len;",
        f"    uint8_t bytes[{RECORD_SIZE}];",
        "    const char* error;",
        "};",
        "",
        "static const InvalidRecordVector kInvalidRecordVectors[] = {",
    ]
    for v in invalid_records():
        b = bytes.fromhex(v["hex"])
        padded = b + bytes(RECORD_SIZE - len(b))
        lines.append(f'    {{"{v["name"]}", {len(b)}, {{{c_bytes(padded)}}}, "{v["error"]}"}},')
    lines += [
        "};",
        f"static const size_t kInvalidRecordVectorCount = {len(invalid_records())};",
        "",
    ]
    return "\n".join(lines)


