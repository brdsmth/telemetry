#!/usr/bin/env python3
"""Generate golden vectors for the wire formats in schema/PROTOCOL.md.

Outputs, all committed:
  schema/vectors/records.json        record codec, for TypeScript and Go tests
  schema/vectors/records_vectors.h   the same, for the firmware's Unity tests
  schema/vectors/ble.json            BLE payloads: advertising, device info,
                                     control commands, status, data chunks
  schema/vectors/ble_vectors.h       the same, for Unity

CI re-runs this script with --check and fails if the committed files differ.

Usage: python3 schema/tools/gen_vectors.py [--check]
"""
