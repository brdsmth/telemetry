RECORD_VERSION = 1
RECORD_SIZE = 20
FLAG_EPOCH_VALID = 0x01

TYPE_SOIL_RESISTANCE_OHMS = 1
TYPE_BATTERY_MILLIVOLTS = 2

QUALITY_OK, QUALITY_LOW, QUALITY_HIGH, QUALITY_OPEN = 0, 1, 2, 3

