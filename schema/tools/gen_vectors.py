def encode_advertising(a: dict) -> bytes:
    return struct.pack("<BHHB", a["protocol_version"], a["pending"], a["battery_mv"], a["adv_flags"])


def encode_device_info(d: dict) -> bytes:
    fw = d["fw_version"].encode("ascii")
    assert len(fw) <= 16
    out = struct.pack(
        "<BB6sHIIIIIIHH16s",
        d["protocol_version"], d["record_size"], bytes.fromhex(d["device_id"]),
        d["boot_id"], d["next_seq"], d["collected_through"], d["secured_through"],
        d["uptime_s"], d["unix_time"], d["dropped"], d["battery_mv"], d["capacity"],
        fw.ljust(16, b"\0"),
    )
    assert len(out) == DEVICE_INFO_SIZE
    return out


def encode_status(s: dict) -> bytes:
    return struct.pack("<BBI", s["opcode"], s["result"], s["seq"])


def encode_command(c: dict) -> bytes:
    op = OPCODES[c["name"]]
    if c["name"] == "OPEN_SESSION":
        return struct.pack("<B", op) + bytes.fromhex(c["session_id"])
    if c["name"] == "SET_TIME":
        return struct.pack("<BI", op, c["unix_time"])
    if c["name"] == "READ_FROM":
        return struct.pack("<BIH", op, c["seq"], c["max_records"])
    if c["name"] in ("ACK_COLLECTED", "ACK_SECURED"):
        return struct.pack("<BI", op, c["through_seq"])
    if c["name"] == "CLOSE_SESSION":
        return struct.pack("<B", op)
    raise ValueError(c["name"])


def encode_chunk(first_seq: int, flags: int, records: list[bytes]) -> bytes:
    body = b"".join(records)
    header = struct.pack("<IBBH", first_seq, len(records), flags, crc16_ccitt_false(body))
    return header + body


